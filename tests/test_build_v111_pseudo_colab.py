"""Contract tests for the v111 test-image pseudolabel notebook (§2.89).

v111 measures the last untried data-side mechanism that preserves honest
fold-2 evaluation: semi-supervised pseudolabels on the competition's own
test images (180), generated by the full production pipeline (fold-2
detector + fold-2 refiner + disjoint ownership). The tests pin the arm
set, the pseudolabel generation path (identical to scoring), the
dataset merge, the OOM batch fallback, the gate/rules-check verdict, and
that frozen cells stay byte-identical.
"""

import ast
import json

import pytest

from scratch import build_v111_pseudo_colab as v111


def _src(cell):
    src = cell["source"]
    return "".join(src) if isinstance(src, list) else src


@pytest.fixture(scope="module")
def nb():
    return json.loads(v111.OUT.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def nb_source():
    return json.loads(v111.SOURCE.read_text(encoding="utf-8"))


def test_all_cells_parse(nb):
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        stripped = "\n".join(
            line for line in _src(cell).splitlines() if not line.lstrip().startswith("%"))
        ast.parse(stripped)


def test_config_declares_v111_arm_and_paths(nb):
    config = _src(nb["cells"][1])
    assert "ARMS = ('pseudotest',)" in config
    assert "TRAIN_FOLDS = (0, 1)" in config
    assert "PSEUDO_CONF = 0.26" in config
    assert "PSEUDO_DIR = None" in config
    for path in ('"runs" / "v111_pseudo"', '"yolo_datasets" / "v111_pseudo"',
                 '"v111_pseudo_colab_manifest.json"', 'Path("/content/solar_v111")'):
        assert path in config, path
    assert "GATE_DELTA = 0.010" in config
    for kept in ("PRIMARY_CONF = 0.26", "CROP_SIZE = 320", "CROP_CONTEXT = 1.65",
                 "REFINER_THRESHOLD = 0.45", "MIN_AREA = 20",
                 "PREDICT_CONF_FLOOR = 0.08", "YOLO_MASK_RATIO = 2",
                 "YOLO_CLS = 0.5", "YOLO_EPOCHS = 70"):
        assert kept in config, kept


def test_dataset_cell_merges_pseudo_and_oom_fallback(nb):
    ds = _src(nb["cells"][3])
    assert '_pseudotest"' in ds  # dataset root suffix
    assert 'if CFG.PSEUDO_DIR is not None:' in ds
    assert '(CFG.PSEUDO_DIR / "labels").glob("*.txt")' in ds
    assert '"pseudo_instances"' in ds
    assert '"pseudo_images"' in ds
    # OOM fallback: batch 4 → 2, single retry, recorded
    assert "for _batch in (CFG.YOLO_BATCH, 2):" in ds
    assert "torch.cuda.OutOfMemoryError" in ds
    assert '"batch_fallback"] = True' in ds
    # prod recipe unchanged
    for arg in ("mask_ratio=CFG.YOLO_MASK_RATIO", "cls=CFG.YOLO_CLS",
                'optimizer="AdamW"', "lr0=7e-4", "warmup_epochs=3",
                "mosaic=0.20", "close_mosaic=10"):
        assert arg in ds, arg


def test_pseudolabel_generation_matches_scoring_path(nb):
    run = _src(nb["cells"][6])
    # teacher = prod fold-2 pipeline; same floor → refine → conf/area → ownership
    assert "conf=CFG.PREDICT_CONF_FLOOR" in run
    assert "iou=CFG.PREDICT_IOU" in run
    assert "retina_masks=True" in run
    assert "conf[i] >= CFG.PSEUDO_CONF and masks[i].sum() >= CFG.MIN_AREA" in run
    assert "refine_proposal(image, masks[i])" in run
    assert "apply_ownership(" in run
    # 180 test images, preprocessed via solar_three_channel q96 fallback
    assert 'rglob("test_images")' in run
    assert "assert len(test_files) == 180" in run
    assert "solar_three_channel" in run
    assert "IMWRITE_JPEG_QUALITY, 96" in run
    # mask → polygon: largest external contour, normalized
    assert "cv2.findContours" in run and "RETR_EXTERNAL" in run
    assert "CHAIN_APPROX_SIMPLE" in run
    assert "max(contours, key=cv2.contourArea)" in run
    # idempotent: per-image writes + COMPLETE marker + stats json
    assert "PSEUDOLABELS_COMPLETE" in run
    assert "pseudolabel_stats.json" in run
    # PSEUDO_DIR derived + stats into manifest datasets before arm loop
    assert 'CFG.PSEUDO_DIR = CFG.YOLO_ROOT / "pseudotest_teacher_f2"' in run
    assert 'manifest["datasets"]["pseudolabels"]' in run


